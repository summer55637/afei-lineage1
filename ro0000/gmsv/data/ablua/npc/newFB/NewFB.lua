			end
		elseif seqno == 1 then
			char.AllWarpToSpecificPoint(talkerindex,3,12,13); --传送地图
		elseif seqno == 2 then            --兑换 道具编号1     道具编号2     道具编号3     道具编号4
			if npc.Free(meindex, talkerindex,"ITEM=22403*1&ITEM=22404*1&ITEM=22405*1&ITEM=22406*1") == 1 then
				npc.DelItem(talkerindex, "22403*1,22404*1,22405*1,22406*1")  --扣除道具
				npc.AddItem(talkerindex,21096)  --获取道具
			else
				char.TalkToCli(talkerindex,meindex, "兑换条件不足", 4)
			end
		elseif seqno > 2 then
			char.DischargeParty(talkerindex, 1)
			if char.getWorkInt(talkerindex,"组队") == 0 then
				local FBdata = GetFBdata(talkerindex)
				if FBdata == true then
					local menemytable = {{4205} --BOSS1
										,{4206}--BOSS2
										,{4207}--BOSS3
										,{4208}}--BOSS4
					battle.CreateVsEnemy(talkerindex,meindex,menemytable[char.getWorkInt(meindex, "NPC临时1")]);
				else
					char.TalkToCli(talkerindex, -1, "今日已挑战2次副本，请明日再来", 4);
				end
			else       
				char.TalkToCli(talkerindex, meindex, "本副本禁止团队战斗", 4);
			end
		end
	end
end

