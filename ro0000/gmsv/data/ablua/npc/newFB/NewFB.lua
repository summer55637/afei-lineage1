function GetFBdata(charaindex)
	sasql.query("select FBdata from NewFB where Account = '"..char.getChar(charaindex,"账号").."'");
	sasql.free_result();
	sasql.store_result();
	if sasql.num_rows() == 1 then
		sasql.fetch_row();
		if other.atoi(other.getString(sasql.data(1), "/", 1)) == other.atoi(os.date("%m%d",os.time())) and other.atoi(other.getString(sasql.data(1), "/", 2)) >= 2 then
			return false
		end
	else
		local fbdata = os.date("%m%d",os.time()).."/0"
		sasql.query("insert into NewFB set FBdata='"..fbdata.."',Account = '"..char.getChar(charaindex,"账号").."',Name ='"..char.getChar(charaindex, "名字").."'")
	end
	return true
end

