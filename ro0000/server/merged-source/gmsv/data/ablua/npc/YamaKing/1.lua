--NPC对话事件(NPC索引)
function Talked(meindex, talkerindex , szMes, color )
	if npc.isFaceToFace(meindex, talkerindex) == 1 then 
		if char.getWorkInt(talkerindex, "组队") ~= 0 then
			char.TalkToCli(talkerindex, -1, "请解散团队后在与我对话！", "随机色")
			return
		end
		token = "                 『" .. char.getChar(meindex, "名字") .. "』\n\n"                       
				 .. "    你想领奖吗?领奖后会自带传出魔王楼层哦！继续轻点确定。!"                                                             
						                                                                                           
		lssproto.windows(talkerindex, "对话框", "确定|取消", 1, char.getWorkInt( meindex, "对象"), token)
	end
end

function checkEmptItemNum(charaindex)
	EmptyItemNum = 0
	for i = 9, 23 do
		if char.getItemIndex(charaindex, i) == -1 then
			EmptyItemNum = EmptyItemNum + 1
		end
	end
	return EmptyItemNum
end

--NPC窗口事件(NPC索引)
function WindowTalked ( meindex, talkerindex, seqno, select, data)
	if npc.isFaceToFace(meindex, talkerindex) == 1 then 
		if seqno == 1 then
			if select == 1 then
				if char.getWorkInt(talkerindex, "组队") ~= 0 then
					char.TalkToCli(talkerindex, -1, "请解散团队后在领取奖励", "随机色")
					return
				end
				if char.getInt(talkerindex, "地图号") ~= 46602 then
					char.talkToServer(-1, "[十殿阎罗]"..char.getChar(talkerindex, "名字").."请在地图内领取奖励。", "随机色")
					return
				end
				if checkEmptItemNum(talkerindex) == 0 then
					char.TalkToCli(talkerindex, meindex, "你的物品栏满咯，这样可没办法领奖哦！", "随机色")
					return
				end
				local ItemNum = table.getn(GiveItemList[1])
				local RandItem = math.random(1,100)
				local GiveItem = ""
				for i = 1,ItemNum do
					if RandItem <= GiveItemListRand[1][i] then
						GiveItem = GiveItemList[1][i]
						break
					end
				end
				local TM_ItemIndex = npc.AddRandItem(talkerindex, GiveItem)
				char.talkToServer(-1, "[十殿阎罗]恭喜勇者 " .. char.getChar(talkerindex, "名字")  .. " 挑战" .. NpcData[3][1] .. "获得 [" .. item.getChar(TM_ItemIndex, "显示名") .."]", "随机色")
				char.WarpToSpecificPoint(talkerindex, 2005, 13, 14)
				
			end
		end
	end
end

function Create(name, metamo, floor, x, y, dir)
	--创建NPC(NPC名字，图像号，地图号，坐标X，坐标Y，方向号)将返回一个NPC索引
	npcindex = npc.CreateNpc(name, metamo, floor, x, y, dir)
	--设置事件触发(NPC索引，事件，执行函数，执行函数文件路径)
	char.setFunctionPointer(npcindex, "对话事件", "Talked", "")
	char.setFunctionPointer(npcindex, "窗口事件", "WindowTalked", "")
end

