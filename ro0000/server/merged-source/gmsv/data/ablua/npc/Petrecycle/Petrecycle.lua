function WindowTalked (meindex, talkerindex, seqno, select, data)
	if npc.isFaceToFace(meindex, talkerindex) == 1 and select ~= 8 then
		if seqno == 0 then
			if data*1 == 1 then
				lssproto.windows(talkerindex, 0, 1, -1, char.getWorkInt( meindex, "对象"), "\n\n\n              赎回系统近期开启")
			elseif data*1 == 2 then
				lssproto.windows(talkerindex, 3, 8, 1, char.getWorkInt( meindex, "对象"), 1);
			elseif data*1 == 3 then
				ShowMsg(meindex, talkerindex,1)
			end
		elseif seqno == 1 then
			local petindex = char.getCharPet(talkerindex,data-1)
			local payment,bill,centtype = petcheck(talkerindex,petindex)
			if payment > 0 then
				local token = "                 [style c=5]〖"..char.getChar(petindex,"名字").."〗[/style]\n\n"
				.."              回收价为：[style c=4]"..payment.."[/style]"..centtype
				.."\n              赎回价为：[style c=2]"..bill.."[/style]"..centtype
				.."\n\n           [style c=21]注意:[/style][style c=20]赎回后宠物将还原未转1级[/style]"
				.."\n              [style c=6]确定后宠物将会回收[/style]"
				lssproto.windows(talkerindex, 0, 12, 2, char.getWorkInt( meindex, "对象"), token)
				char.setWorkInt(talkerindex, "NPC临时1", petindex)
				char.setWorkInt(talkerindex, "NPC临时2", bill)
				char.setWorkInt(talkerindex, "NPC临时3", payment)
				char.setWorkChar(talkerindex, "NPC临时4", centtype)
			end
		elseif seqno == 2 then
			local petindex,paytype = char.getWorkInt(talkerindex, "NPC临时1"),0
			if char.check(petindex) == 1 then
				if char.getInt(petindex,"守护兽") ~= 3 then
					if char.getWorkChar(talkerindex, "NPC临时4") == "金币" then
						sasql.setVipPoint(talkerindex, sasql.getVipPoint(talkerindex)+char.getWorkInt(talkerindex, "NPC临时3"))
						paytype = 1
					else
						sasql.setPetPoint(talkerindex, sasql.getPetPoint(talkerindex)+char.getWorkInt(talkerindex, "NPC临时3"))
					end
					sasql.query("insert into Petrecycle values ('"..char.getChar(talkerindex, "账号")
					.."',"..char.getInt(petindex,"宠ID")..","..char.getWorkInt(talkerindex, "NPC临时2")..","..paytype..",NOW())")
					local token = "\n\n\n                  [style c=6]回收成功[/style]\n\n"
					.."              获得[style c=4]"..char.getWorkInt(talkerindex, "NPC临时3").."[/style]"..char.getWorkChar(talkerindex, "NPC临时4")
					lssproto.windows(talkerindex, 0, 1, -1, char.getWorkInt( meindex, "对象"), token)
					char.talkToAllServer("P|P|[宠物回收]玩家"..char.getChar(talkerindex, "名字").."在宠物典当员回收了精品宠物"..char.getChar(petindex,"名字").."，如有需要的玩家可前往赎回此宠物","")
					char.DelPet(talkerindex,petindex)
				else
					char.newMessageToCli(talkerindex,-1,"家族守护兽无法进行回收",4)
				end
			end
		elseif seqno > 10 then
			if select == 32 then
				ShowMsg(meindex, talkerindex, seqno-9)
			elseif select == 16 then
				ShowMsg(meindex, talkerindex, seqno-11)
			end
		end
	end
end

function petcheck(talkerindex,petindex)
	local qualified,num,point = false,0,char.getWorkInt(petindex,"最大HP")/4 + char.getWorkInt(petindex,"攻击力") + char.getWorkInt(petindex,"防御力") + char.getWorkInt(petindex,"敏捷力")
	for i=1,#petlist do
		if char.getInt(petindex,"宠ID") == petlist[i][1] then
			qualified,num = true,petlist[i][2][#petlist[i][2]]
			for j=1,#petlist[i][2] do
				if point >= petlist[i][2][j] then
					return petlist[i][3][j],petlist[i][4][j],"金币"
				end
			end
		end
	end
	for i=1,#petlist2 do
		if char.getInt(petindex,"宠ID") == petlist2[i][1] then
			qualified,num = true,petlist2[i][2][#petlist2[i][2]]
			for j=1,#petlist2[i][2] do
				if point >= petlist2[i][2][j] then
					return petlist2[i][3][j],petlist2[i][4][j],"水晶"
				end
			end
		end
	end
	if qualified then
		char.newMessageToCli(talkerindex,-1,char.getChar(petindex,"名字").."的评分必须大于等于："..num, 4)
	else
		char.newMessageToCli(talkerindex,-1,"您选择的宠物无法回收", 4)
	end
	return 0
end

