	"\n    4，梦宠类---圣兽类---魔兽类 均回收为金币\n    普通商宠2D回收均为水晶\n\n    5，宠物赎回后均为1级状态，赎回功能暂未开放\n    玩家自愿行为\n    回收或赎回后均不可更改找回或取消，切记"}
