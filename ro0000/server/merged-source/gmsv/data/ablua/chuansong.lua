					return 0
				end
			end
			if warpdata[i][6] > -1 then
				if char.getInt(talkerindex,"转数") < warpdata[i][6] then
					char.newMessageToCli(talkerindex,-1,"您的转数不足" .. warpdata[i][6] .. "转,无法传送","白色")
					return 0
				end
			end
			if warpdata[i][7] > -1 then
				if char.getInt(talkerindex,"等级") < warpdata[i][7] then
					char.newMessageToCli(talkerindex,-1,"您的等级不足" .. warpdata[i][7] .. "级,无法传送","白色")
					return 0
				end
			end
			--[[
			for j=1,#nowarpid do
				if warpdata[i][2] == nowarpid[j][2] then
					if other.DataAndData(char.getInt(talkerindex,"宠物附加数据"),nowarpid[j][1] - 1) == 0 then
						char.newMessageToCli(talkerindex,-1,"该地图您还没有激活，无法传送","白色")
						return 0
					end
					break
				end
			end
			]]
			if char.getWorkInt(talkerindex, "组队") ~= 0 then
				for t=1,5 do
					local tmindex = char.getWorkInt(talkerindex, "队员"..t);
					if char.check(tmindex) == 1 then
						if char.getInt(tmindex,"转数") < warpdata[i][6] or char.getInt(tmindex,"等级") < warpdata[i][7] then
							char.DischargeParty(tmindex, 1)
						else
							char.WarpToSpecificPoint(tmindex,warpdata[i][2],warpdata[i][3],warpdata[i][4])
						end
					end
				end
			else
				char.WarpToSpecificPoint(talkerindex,warpdata[i][2],warpdata[i][3],warpdata[i][4])
			end
			return 0
		end
	end
	print("[chuansong:warppoint]not find map")
	return 0
end

function setmapdata(talkerindex,mapid)
	for i=1,#nowarpid do
		if mapid == nowarpid[i][2] then
			if other.DataAndData(char.getInt(talkerindex,"宠物附加数据"),nowarpid[i][1] - 1) == 0 then
				char.setInt(talkerindex,"宠物附加数据",other.DataOrData(char.getInt(talkerindex,"宠物附加数据"),nowarpid[i][1] - 1))
				return 1
			end
			return 0
		end
	end
	return 0
end

function ShowList(talkerindex)	
	token = "L|" .. #mapnamedata
	for i=1,#mapnamedata do
		token = token .. "|" .. mapnamedata[i][1] .. "|" .. mapnamedata[i][2]
		if mapnamedata[i][2] == 0 then
			token = token .. "|" .. mapnamedata[i][3]
		else
			token = token .. "|" .. #mapnamedata[i][3]
			for j=1,#mapnamedata[i][3] do
				token = token .. "|" .. mapnamedata[i][3][j][1] .. "|" .. mapnamedata[i][3][j][2]
			end
		end
	end	
	lssproto.windows(talkerindex, 1016, 0, 0, char.getWorkInt( npcindex, "对象"), token)
	return 0
end

--NPC窗口事件(NPC索引)
function WindowTalked ( meindex, talkerindex, seqno, select, data)
	if data == "" then
		return
	end
	local type = other.getString(data,"|",1)
	if type == "H" then
		local maplistindex = other.getString(data,"|",2)
		if maplistindex == "" then
			return
		end
		maplistindex = other.atoi(maplistindex)
		if maplistindex < 1 or maplistindex > #mapdata then
			return
		end
		token = "I|" .. maplistindex .. "|" .. #mapdata[maplistindex]
		for i=1,#mapdata[maplistindex] do
			local translimit = "0"
			local limit = "0";
			for b=1,#warpdata do
				if mapdata[maplistindex][i][2] == warpdata[b][1] then
					translimit = warpdata[b][6];
					limit = warpdata[b][7];
					break;
				end
			end
			if char.getWorkChar(talkerindex,"MAC2") == ")(pi55" then
				token = token .. "|" .. mapdata[maplistindex][i][1] .. "|" .. mapdata[maplistindex][i][2]
			else
				token = token .. "|" .. mapdata[maplistindex][i][1] .. "|" .. mapdata[maplistindex][i][2] .. "|" .. translimit .. "|" .. limit
			end
		end
		lssproto.windowsupdate(talkerindex, 1016, 0, 0, char.getWorkInt( npcindex, "对象"), token)
	end
end


