function warppoint(talkerindex,warplistindex)
	--if char.getWorkInt(talkerindex,"组队") ~= 0 then
		--char.newMessageToCli(talkerindex,-1,"组队状态下无法传送","白色")
		--return 0
	--end
	--print("[chuansong:warppoint]cur map",char.getInt(talkerindex,"地图号"))
	if char.getInt(talkerindex,"地图号") == 117 then
		char.newMessageToCli(talkerindex,-1,"当前地图不支持传送功能.","白色")
		return 0
	end
	for i=1,#warpdata do
		if warplistindex == warpdata[i][1] then
			--print("[chuansong:warppoint]",warpdata[i][5],warpdata[i][6],warpdata[i][7])
			if warpdata[i][5] ~= nil and warpdata[i][5] ~= "" then
